_BY_ID: dict[str, ChannelSpec] = {c.id: c for c in _REGISTRY}


# ── Selection API ───────────────────────────────────────────────────────


def all_channels() -> tuple[ChannelSpec, ...]:
    """Every registry row, in canonical display order."""
    return _REGISTRY


def get(channel_id: str) -> Optional[ChannelSpec]:
    """Look up one row by id (case-insensitive), or None if unknown."""
    if not isinstance(channel_id, str):
        return None
    return _BY_ID.get(channel_id.strip().lower())


def where(predicate: Callable[[ChannelSpec], bool]) -> tuple[ChannelSpec, ...]:
    """Rows matching ``predicate``, in canonical display order.

    This is the ONLY sanctioned way for a consumer to narrow the registry.
    Never copy a subset of ids into your module — declare the capability you
    need and filter on it, so a new channel row updates you for free and an
    unsupported one keeps you honest.
    """
    return tuple(c for c in _REGISTRY if predicate(c))


def ids_where(predicate: Callable[[ChannelSpec], bool]) -> tuple[str, ...]:
    """Channel ids matching ``predicate``, in canonical display order."""
    return tuple(c.id for c in where(predicate))


def labels_where(
    predicate: Callable[[ChannelSpec], bool],
    *,
    prose: bool = False,
) -> dict[str, str]:
    """``{id: label}`` for rows matching ``predicate``.

    ``prose=True`` selects :attr:`ChannelSpec.prose_label` (mid-sentence
    form) instead of the product-name ``display_label``.
    """
    return {
        c.id: (c.prose_label if prose else c.display_label)
        for c in where(predicate)
    }


def by_notify_priority() -> tuple[str, ...]:
    """Channel ids that Evolve can SEND to, in notify-fallback order.

    Backs both ``breakers_enforce._USER_CHANNEL_PRIORITY`` (per-bot OOO
    posting) and ``alerts.dispatcher._DEFAULT_CHANNEL_PRIORITY`` (operator
    alerts). Those two tables were byte-identical by coincidence; deriving
    both from ``notify_priority`` makes it structural.
    """
    ranked = [c for c in _REGISTRY if c.notify_priority is not None]
    ranked.sort(key=lambda c: c.notify_priority)  # type: ignore[arg-type,return-value]
    return tuple(c.id for c in ranked)


def pairing_channels() -> tuple[ChannelSpec, ...]:
    """Rows with a pairing config — the channels the Users UI surfaces."""
    return where(lambda c: c.supports_pairing)


def pairing_channel_ids() -> tuple[str, ...]:
    """Ids of the pairing-capable channels, in display order."""
    return ids_where(lambda c: c.supports_pairing)


def name_resolution_channels() -> frozenset[str]:
    """Channels with a working name-resolution adapter.

    Narrow ON PURPOSE — this is the canonical example of why the registry
    has capability columns. Widening it to "all channels" would make
    ``evo.name_resolver`` claim support it does not have.
    """
    return frozenset(ids_where(lambda c: c.supports_name_resolution))


def verify_handlers() -> dict[str, str]:
    """``{channel_id: wizard_verify handler name}`` for verifiable channels."""
    return {
        c.id: c.verify_handler
        for c in _REGISTRY
        if c.verify_handler is not None
    }


def messaging_integration_ids() -> frozenset[str]:
    """Channel ids that count as "messaging-capable" for the app coherence
    gate. Excludes ``webhook`` (a delivery sink, not a channel)."""
    return frozenset(ids_where(lambda c: c.messaging_integration))


def known_ids() -> frozenset[str]:
    """Every id in the registry. Use a narrower selector unless you genuinely
    mean "any channel Evolve has heard of"."""
    return frozenset(_BY_ID)


def display_label(channel_id: str, *, prose: bool = False) -> str:
    """Operator-facing name for a channel id, with a title-case fallback so an
    unregistered id still reads like a product name."""
    spec = get(channel_id)
    if spec is not None:
        return spec.prose_label if prose else spec.display_label
    cid = (channel_id or "").strip()
    return cid.title()


def iter_ids(specs: Iterable[ChannelSpec]) -> tuple[str, ...]:
    """Small helper: ids out of a row iterable, order preserved."""
    return tuple(c.id for c in specs)
