# ── In-process laptop-side install/uninstall/status ─────────────────────────


def _resolve_ssh_key(ssh_key: str) -> Path:
    return Path(os.path.expanduser(ssh_key))


def _ssh_args(
    remote_host: str,
    remote_user: str,
    remote_port: int,
    local_port: int,
    ssh_key: Path | None,
) -> list[str]:
    args: list[str] = []
    if ssh_key and ssh_key.exists():
        args += ["-i", str(ssh_key)]
    args += [
        "-o", "ServerAliveInterval=30",
        "-o", "ServerAliveCountMax=3",
        "-o", "ExitOnForwardFailure=yes",
        "-N",
        "-L", f"{local_port}:localhost:{remote_port}",
    ]
    target = f"{remote_user}@{remote_host}" if remote_user else remote_host
    args.append(target)
    return args


def _autossh_path() -> str | None:
    """Return path to autossh if installed, else None."""
    return shutil.which("autossh")


def _build_plist_xml(
    program: str,
    program_args: list[str],
    log_path: Path,
    keep_alive: bool = True,
) -> str:
    """Render the tunnel LaunchAgent plist (pure — no disk access).

    ``keep_alive=False`` omits the KeepAlive key (launchd's default is
    false) — the old hand-rolled emitter wrote an explicit <false/>;
    behaviorally identical, and no caller passes False today.
    """
    return render_launchd_plist(JobSpec(
        label=TUNNEL_LABEL,
        program_args=[program, *program_args],
        run_at_load=True,
        keep_alive=keep_alive,
        stdout_path=str(log_path),
        stderr_path=str(log_path),
    ))


def install_persistent_tunnel(cfg: TunnelConfig) -> dict:
    """Install (or reinstall) the persistent SSH tunnel launchd agent.

    Idempotent: if the agent is already loaded, it is reloaded with the new
    plist. Prefers autossh when present (reliable auto-reconnect on flap),
    falls back to plain /usr/bin/ssh otherwise.

    Returns a dict with keys: plist_path, log_path, used_autossh, label.
    """
    remote_host = cfg.get("remote_host") or _autodetect_remote_host()
    remote_user = cfg.get("remote_user") or _autodetect_remote_user()
    remote_port = int(cfg.get("remote_port", 5050))
    local_port = int(cfg.get("local_port", 5050))
    ssh_key = _resolve_ssh_key(cfg.get("ssh_key", "~/.ssh/id_ed25519"))

    if not remote_host:
        raise RuntimeError(
            "remote_host is required — pass --host or set adminBaseUrl in network.json"
        )

    plist = _plist_path()
    log = _log_path()
    log.parent.mkdir(parents=True, exist_ok=True)
    plist.parent.mkdir(parents=True, exist_ok=True)

    autossh = _autossh_path()
    if autossh:
        program = autossh
        program_args = ["-M", "0", *_ssh_args(remote_host, remote_user, remote_port, local_port, ssh_key)]
    else:
        program = "/usr/bin/ssh"
        program_args = _ssh_args(remote_host, remote_user, remote_port, local_port, ssh_key)

    plist.write_text(_build_plist_xml(program, program_args, log))

    # Reload if already loaded (gui-session legacy verbs — see module note)
    _rc, listed_out, _err = _agent_launchctl.raw("list")
    if TUNNEL_LABEL in listed_out:
        _agent_launchctl.raw("unload", str(plist))

    load_rc, _out, load_err = _agent_launchctl.raw("load", str(plist))
    if load_rc != 0:
        raise RuntimeError(f"launchctl load failed: {load_err.strip()}")

    return {
        "plist_path": str(plist),
        "log_path": str(log),
        "used_autossh": bool(autossh),
        "label": TUNNEL_LABEL,
        "remote_host": remote_host,
        "remote_user": remote_user,
        "remote_port": remote_port,
        "local_port": local_port,
        "ssh_key_present": ssh_key.exists(),
    }


def uninstall_persistent_tunnel() -> dict:
    """Stop and remove the persistent tunnel launchd agent.

    Returns {"removed": bool, "plist_path": str}. Safe to call when nothing
    is installed — returns removed=False.
    """
    plist = _plist_path()
    if not plist.exists():
        return {"removed": False, "plist_path": str(plist)}

    _agent_launchctl.raw("unload", str(plist))
    plist.unlink()
    return {"removed": True, "plist_path": str(plist)}


def tunnel_status(local_port: int = 5050) -> dict:
    """Inspect the tunnel agent and port to decide if it's actually up.

    Returns a dict with keys:
      installed (bool)            — plist file exists
      loaded (bool)               — launchctl knows about the label
      pid (int | None)            — process id if running
      listening_on_local (bool)   — something is on local_port
      plist_path (str)
      log_path (str)
    """
    plist = _plist_path()
    info: dict = {
        "installed": plist.exists(),
        "loaded": False,
        "pid": None,
        "listening_on_local": False,
        "plist_path": str(plist),
        "log_path": str(_log_path()),
    }

    _rc, listed_out, _err = _agent_launchctl.raw("list")
    for line in listed_out.splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[-1] == TUNNEL_LABEL:
            info["loaded"] = True
            try:
                info["pid"] = int(parts[0]) if parts[0] != "-" else None
            except ValueError:
                info["pid"] = None
            break

    lsof = subprocess.run(
        ["lsof", "-iTCP", f"-i:{local_port}", "-sTCP:LISTEN", "-P", "-n"],
        capture_output=True, text=True,
    )
    info["listening_on_local"] = bool(lsof.stdout.strip())
    return info


def run_one_shot_tunnel(cfg: TunnelConfig) -> int:
    """Exec a foreground ssh tunnel; blocks until Ctrl+C or remote drop.

    Returns the ssh exit code. Does not install or touch launchd.
    """
    remote_host = cfg.get("remote_host") or _autodetect_remote_host()
    remote_user = cfg.get("remote_user") or _autodetect_remote_user()
    remote_port = int(cfg.get("remote_port", 5050))
    local_port = int(cfg.get("local_port", 5050))
    ssh_key = _resolve_ssh_key(cfg.get("ssh_key", "~/.ssh/id_ed25519"))

    if not remote_host:
        raise RuntimeError(
            "remote_host is required — pass --host or set adminBaseUrl in network.json"
        )

    cmd = ["/usr/bin/ssh", *_ssh_args(remote_host, remote_user, remote_port, local_port, ssh_key)]
    return subprocess.call(cmd)


